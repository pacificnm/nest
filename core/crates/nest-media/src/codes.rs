/// Media entity was not found.
pub const NEST_MEDIA_NOT_FOUND: &str = "NEST_MEDIA_NOT_FOUND";

/// Invalid media input or field value.
pub const NEST_MEDIA_INVALID_INPUT: &str = "NEST_MEDIA_INVALID_INPUT";

/// Metadata provider operation failed.
pub const NEST_MEDIA_PROVIDER_FAILED: &str = "NEST_MEDIA_PROVIDER_FAILED";

/// Media library repository operation failed.
pub const NEST_MEDIA_REPOSITORY_FAILED: &str = "NEST_MEDIA_REPOSITORY_FAILED";

/// Media inspection operation failed.
pub const NEST_MEDIA_INSPECTION_FAILED: &str = "NEST_MEDIA_INSPECTION_FAILED";

/// Media configuration error.
pub const NEST_MEDIA_CONFIG: &str = "NEST_MEDIA_CONFIG";
